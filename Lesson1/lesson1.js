// isPrime(7);
// Output:
// true

console.log("/*==========================================================Bai 14=================================================================================*/")

const isPrime = (number) => {
    if (number < 2)
        return false;
    if (number === 2)
        return true;
    for(let i = 2; i < number; i++){
        if(number % i === 0)
            return false;
    }
    return true;
};

